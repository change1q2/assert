export function getStrategySummary() {
  const sections = STRATEGY_FRAMEWORK.sections;
  return {
    title: STRATEGY_FRAMEWORK.title,
    subtitle: STRATEGY_FRAMEWORK.subtitle,
    sections: sections.map((s) => ({
      id: s.id,
      title: s.title,
      icon: s.icon,
    })),
    total_sections: sections.length,
  };
}

export function getStrategySection(sectionId) {
  for (const s of STRATEGY_FRAMEWORK.sections) {
    if (s.id === sectionId) {
      return {
        id: s.id,
        title: s.title,
        icon: s.icon,
        content: s.content,
      };
    }
  }
  return null;
}

export function getAllStrategyContent() {
  let md = `# ${STRATEGY_FRAMEWORK.title}\n\n`;
  md += `> ${STRATEGY_FRAMEWORK.subtitle}\n\n`;
  md += '---\n\n';
  for (const s of STRATEGY_FRAMEWORK.sections) {
    md += `## ${s.icon} ${s.title}\n\n`;
    md += s.content;
    md += '\n\n---\n\n';
  }
  return md;
}

